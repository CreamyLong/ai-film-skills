#!/usr/bin/env python3
"""Turn audit findings into a technical repair plan.

Reads one or more audit result JSON files (as written by episode_audit.py),
classifies each finding into a defect class, assigns a repair owner/action and
emits commands against the episode package. It does not execute anything.

The classification is deterministic and intentionally conservative: a finding
that cannot be mapped stays ``unclassified`` and needs a human.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

RULES = [
    ("identity_mismatch", ("T1",), r"不是同一人|并非同一人|不同人|换脸|造型突变|身份不符"),
    ("burned_text", ("T1", "T2", "T3"), r"烧录字幕|台词字幕|伪文字|乱码|文字贴图"),
    ("space_break", ("T3",), r"不属于同一个房间|不属于同一房间|空间不一致|空间跳变|换房|背景.*跳"),
    ("audio_break", ("T4",), r"响度跳变|底噪变化|房间声断裂|爆音|鬼声"),
    ("artifact", ("T5", "T6"), r"多指|多余手指|畸形手|断肢|重影|残影|拖影|叠影|漂浮|穿模"),
    ("sequence_clarity", ("T5",), r"分不清|关系.*不清|没有铺垫|无源|轴线"),
]

ACTIONS = {
    "identity_mismatch": {
        "owner": "asset/prompt/generation",
        "root_cause": "reference_not_on_screen_character_or_steps_too_low",
        "action": "check face ref, rerender at 8 steps with a new seed",
        "verify": "reference-vs-frame identity pair",
    },
    "burned_text": {
        "owner": "prompt/generation",
        "root_cause": "quoted dialogue or technical wording in prompt",
        "action": "remove quotes/specs, rerender, or move text to a still",
        "verify": "six-frame caption sheet",
    },
    "space_break": {
        "owner": "asset/generation",
        "root_cause": "wrong or missing scene reference",
        "action": "bind one scene image across the block, rerender affected shots",
        "verify": "10-12 frame scene grid",
    },
    "audio_break": {
        "owner": "edit/sound",
        "root_cause": "per-shot level gap or dialogue source under a still",
        "action": "align shot gains, retarget still tone_from, rebuild with L-cut",
        "verify": "cut-point A/B audio",
    },
    "artifact": {
        "owner": "generation/asset",
        "root_cause": "too few steps, hands/props generated by video model, bad seed",
        "action": "rerender at 8 steps or replace with a real still",
        "verify": "5 s clip artifact review",
    },
    "sequence_clarity": {
        "owner": "edit/storyboard",
        "root_cause": "missing establishing/reaction shot or broken axis",
        "action": "add coverage, recut, do not explain in dialogue",
        "verify": "12-frame sequence review",
    },
}


def classify(tier: str, text: str) -> str:
    for name, tiers, pattern in RULES:
        if tier in tiers and re.search(pattern, text):
            return name
    return "unclassified"


def shot_of(item_id: str) -> str | None:
    match = re.search(r"shot(\w+)", item_id)
    return match.group(1) if match else None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", nargs="+", type=Path)
    parser.add_argument("--episode-dir", type=Path, required=True,
                        help="episode package root, e.g. 制作/EP019")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    episode = args.episode_dir.resolve()
    ep_name = episode.name
    gen = episode / "scripts" / ("gen_video" + "_v2.py")
    assemble = episode / "scripts" / ("assemble_" + ep_name.lower() + ".py")

    findings = []
    for path in args.results:
        for item in json.loads(path.read_text(encoding="utf-8")):
            text = (item.get("result") or {}).get("text", "")
            if not text:
                continue
            tier = item["id"].split("-")[0]
            defect = classify(tier, text)
            shot = shot_of(item["id"])
            action = ACTIONS.get(defect)
            entry = {
                "id": item["id"], "tier": tier, "shot": shot, "defect": defect,
                "model_excerpt": " ".join(text.split())[:180],
                "human_status": "pending",
            }
            if action:
                entry.update(action)
                commands = []
                if shot and gen.exists():
                    commands.append(
                        f"cd {episode} && python3 scripts/<generation-entry> --shots {shot} "
                        "--steps 8 --force")
                if shot and assemble.exists():
                    commands.append(
                        f"cd {episode} && python3 scripts/<assembly-entry> "
                        "--config edit/editlist.json")
                entry["commands"] = commands
            findings.append(entry)

    order = {"blocker": 0, "major": 1, "minor": 2}
    for entry in findings:
        if entry["defect"] in {"identity_mismatch", "burned_text", "space_break", "audio_break"}:
            entry["severity_hint"] = "major"
        elif entry["defect"] == "artifact":
            entry["severity_hint"] = "major"
        else:
            entry["severity_hint"] = "review"
    findings.sort(key=lambda item: (item["defect"] == "unclassified",
                                    order.get(item["severity_hint"], 3), item["id"]))

    plan = {"episode": ep_name, "findings": findings,
            "note": "Evidence routing only; human confirms severity and root cause."}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [f"# {ep_name} 修复计划", ""]
    for entry in findings:
        lines.append(f"- **{entry['id']}** `{entry['defect']}` ({entry.get('severity_hint')})")
        if entry.get("root_cause"):
            lines.append(f"  - 根因: {entry['root_cause']}")
            lines.append(f"  - 动作: {entry['action']}")
            lines.append(f"  - 复验: {entry['verify']}")
        lines.append(f"  - 模型: {entry['model_excerpt']}")
    md = args.out.with_suffix(".md")
    md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} and {md} ({len(findings)} findings)")


if __name__ == "__main__":
    main()
